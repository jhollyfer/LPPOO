// Aula 01 · Exemplo 05 · Atribuição e operadores aritméticos
// Figurinhas da copa: ganhei, troquei e dividi com meu irmão.

let figurinhas = 40
figurinhas += 12 // ganhei um pacote: 52
figurinhas -= 8 // troquei as repetidas: 44
figurinhas /= 2 // dividi com meu irmão: 22
console.log(`Minha parte: ${figurinhas}`) // Minha parte: 22

const media = (8 + 6) / 2
console.log(`Média das provas: ${media}`) // 7, por causa dos parênteses
console.log(`Resto de 17 por 5: ${17 % 5}`) // 2
