// Figurinhas da copa: ganhei, troquei e dividi com meu irmão.

let figurinhas = 40
console.log(`Comecei com ${figurinhas}`)

figurinhas += 12 // ganhei um pacote
console.log(`Depois do pacote: ${figurinhas}`)

figurinhas -= 8 // troquei as repetidas
console.log(`Depois da troca: ${figurinhas}`)

figurinhas /= 2 // dividi com meu irmão
console.log(`Minha parte: ${figurinhas}`)

const media = (8 + 6) / 2
console.log(`Média das provas: ${media}`) // 7, por causa dos parênteses

console.log(`Resto de 17 por 5: ${17 % 5}`) // 2
